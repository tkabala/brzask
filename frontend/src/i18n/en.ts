// Plural forms English does not have (Polish uses few and many).
type ExtraPlurals = Partial<Record<`${string}_${'zero' | 'two' | 'few' | 'many'}`, string>>

// Every language has these keys, and may add plural forms.
type Strings<T> = {
  [K in keyof T]: T[K] extends string ? string : Strings<T[K]> & ExtraPlurals
}
export type Resources = Strings<typeof en>
